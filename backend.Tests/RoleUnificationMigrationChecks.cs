using Npgsql;

internal static class RoleUnificationMigrationChecks
{
    public static async Task RunAsync()
    {
        var value = Environment.GetEnvironmentVariable("DOCUMENT_TEST_CONNECTION");
        if (string.IsNullOrEmpty(value)) return;
        if (new NpgsqlConnectionStringBuilder(value).Database != "document_checks")
            throw new Exception("Isolated database required.");

        await using var db = new NpgsqlConnection(value);
        await db.OpenAsync();
        async Task Execute(string sql) { await using var cmd = new NpgsqlCommand(sql, db); await cmd.ExecuteNonQueryAsync(); }

        var migration = File.ReadAllText("database/migrations/20261127_unify_admin_into_department_head.sql")
            .Replace("BEGIN;", "")
            .Replace("COMMIT;", "");

        await Execute("CREATE SCHEMA qa_role_unification; SET search_path TO qa_role_unification");
        try
        {
            await Execute("""
                CREATE TABLE roles (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name varchar(50) NOT NULL,
                    description text NULL,
                    updated_at timestamptz NOT NULL DEFAULT now(),
                    deleted_at timestamptz NULL
                );
                CREATE UNIQUE INDEX uq_roles__name ON roles (name) WHERE deleted_at IS NULL;

                CREATE TABLE users (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username varchar(254) NOT NULL,
                    session_version integer NOT NULL DEFAULT 0,
                    updated_at timestamptz NOT NULL DEFAULT now(),
                    deleted_at timestamptz NULL
                );

                CREATE TABLE user_roles (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id bigint NOT NULL REFERENCES users(id),
                    role_id bigint NOT NULL REFERENCES roles(id),
                    updated_at timestamptz NOT NULL DEFAULT now(),
                    deleted_at timestamptz NULL
                );
                CREATE UNIQUE INDEX uq_user_roles__user_role ON user_roles (user_id, role_id) WHERE deleted_at IS NULL;

                INSERT INTO roles (id, name, description) VALUES
                    (1, 'admin', 'Administrador'),
                    (2, 'department_head', 'Jefatura'),
                    (3, 'social_service_officer', 'SS'),
                    (4, 'company_supervisor', 'Supervisor externo');
                SELECT setval(pg_get_serial_sequence('roles', 'id'), 4);

                INSERT INTO users (id, username, session_version) VALUES
                    (1, 'legacy.admin', 0),
                    (2, 'dual.head', 0),
                    (3, 'officer.ss', 0);
                SELECT setval(pg_get_serial_sequence('users', 'id'), 3);

                INSERT INTO user_roles (user_id, role_id) VALUES
                    (1, 1),
                    (2, 1),
                    (2, 2),
                    (3, 3);
                """);

            // 1. Preflight debe abortar si existe algún usuario activo con company_supervisor.
            await using (var tx = await db.BeginTransactionAsync())
            {
                try
                {
                    await Execute("INSERT INTO user_roles (user_id, role_id) VALUES (3, 4)");
                    try
                    {
                        await Execute(migration);
                        throw new Exception("Migration succeeded despite active company_supervisor assignment.");
                    }
                    catch (PostgresException ex) when (ex.SqlState == "P0001") { }
                }
                finally { await tx.RollbackAsync(); }
            }

            // 2. Migración limpia: reasigna admin -> department_head (incluye usuario dual sin 23505),
            //    incrementa session_version de migrados y aplica soft-delete a admin y company_supervisor.
            await using (var tx = await db.BeginTransactionAsync())
            {
                await Execute(migration);
                await tx.CommitAsync();
            }

            // 3. Idempotencia: segunda ejecución no falla ni incrementa session_version otra vez.
            await using (var tx = await db.BeginTransactionAsync())
            {
                await Execute(migration);
                await tx.CommitAsync();
            }

            await using var verify = new NpgsqlCommand("""
                SELECT
                    (SELECT count(*) FROM roles WHERE name IN ('admin', 'company_supervisor') AND deleted_at IS NULL) = 0
                    AND (SELECT count(*) FROM user_roles ur JOIN roles r ON r.id = ur.role_id
                         WHERE ur.user_id = 1 AND r.name = 'department_head' AND ur.deleted_at IS NULL) = 1
                    AND (SELECT count(*) FROM user_roles ur JOIN roles r ON r.id = ur.role_id
                         WHERE ur.user_id = 2 AND r.name = 'department_head' AND ur.deleted_at IS NULL) = 1
                    AND (SELECT count(*) FROM user_roles ur JOIN roles r ON r.id = ur.role_id
                         WHERE ur.user_id = 3 AND r.name = 'social_service_officer' AND ur.deleted_at IS NULL) = 1
                    AND (SELECT session_version FROM users WHERE id = 1) = 1
                    AND (SELECT session_version FROM users WHERE id = 2) = 1
                    AND (SELECT session_version FROM users WHERE id = 3) = 0
                """, db);
            if ((bool?)await verify.ExecuteScalarAsync() != true)
                throw new Exception("Role unification migration verification failed.");
        }
        finally
        {
            await Execute("SET search_path TO public; DROP SCHEMA qa_role_unification CASCADE");
        }

        Console.WriteLine("Role unification migration (admin -> department_head, company_supervisor preflight, idempotency) passed.");
    }
}

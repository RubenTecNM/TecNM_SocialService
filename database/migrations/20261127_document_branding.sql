BEGIN;
ALTER TABLE document_template_versions ADD COLUMN authority_compatibility_for_id bigint;
ALTER TABLE document_template_versions ADD CONSTRAINT fk_document_template_authority_compatibility
    FOREIGN KEY (template_key, authority_compatibility_for_id) REFERENCES document_template_versions(template_key, id);
CREATE UNIQUE INDEX uq_document_template_authority_compatibility
    ON document_template_versions(authority_compatibility_for_id) WHERE authority_compatibility_for_id IS NOT NULL;
CREATE UNIQUE INDEX uq_institutional_authorities_active_role
    ON institutional_authorities(role_key) WHERE is_active AND deleted_at IS NULL;
CREATE TABLE document_logos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    png bytea NOT NULL CHECK (octet_length(png) BETWEEN 1 AND 2097152),
    width integer NOT NULL CHECK (width BETWEEN 1 AND 4096),
    height integer NOT NULL CHECK (height BETWEEN 1 AND 4096),
    sha256 char(64) NOT NULL,
    created_at timestamptz NOT NULL,
    created_by bigint REFERENCES users(id)
);
CREATE TABLE document_template_logos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id bigint NOT NULL REFERENCES document_template_versions(id) ON DELETE CASCADE,
    slot integer NOT NULL,
    logo_id bigint NOT NULL REFERENCES document_logos(id),
    x double precision NOT NULL,
    y double precision NOT NULL,
    width double precision NOT NULL,
    height double precision NOT NULL,
    UNIQUE (version_id, slot)
);
COMMIT;

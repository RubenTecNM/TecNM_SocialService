BEGIN;
CREATE TABLE document_templates (
    key varchar(80) PRIMARY KEY,
    area varchar(20) NOT NULL CHECK (area IN ('social_service', 'internship')),
    mode varchar(12) NOT NULL CHECK (mode IN ('prefill', 'static')),
    active_version_id bigint
);
CREATE TABLE document_template_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_key varchar(80) NOT NULL REFERENCES document_templates(key),
    source_version_id bigint,
    pdf bytea NOT NULL CHECK (octet_length(pdf) BETWEEN 1 AND 5242880),
    sha256 varchar(64) NOT NULL,
    layout jsonb NOT NULL,
    layout_schema_version integer NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL,
    created_by bigint REFERENCES users(id),
    updated_at timestamptz NOT NULL,
    updated_by bigint REFERENCES users(id),
    published_at timestamptz,
    UNIQUE (template_key, id),
    FOREIGN KEY (template_key, source_version_id) REFERENCES document_template_versions(template_key, id)
);
CREATE UNIQUE INDEX uq_document_template_versions_draft
    ON document_template_versions(template_key) WHERE published_at IS NULL;
ALTER TABLE document_templates ADD CONSTRAINT fk_document_templates_active_version
    FOREIGN KEY (key, active_version_id) REFERENCES document_template_versions(template_key, id);
CREATE TABLE document_template_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_key varchar(80) NOT NULL,
    version_id bigint NOT NULL,
    social_service_id bigint REFERENCES social_services(id),
    internship_id bigint REFERENCES internships(id),
    CHECK ((social_service_id IS NULL) <> (internship_id IS NULL)),
    FOREIGN KEY (template_key, version_id) REFERENCES document_template_versions(template_key, id),
    UNIQUE (social_service_id, template_key),
    UNIQUE (internship_id, template_key)
);
CREATE TABLE document_template_activations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_key varchar(80) NOT NULL,
    previous_version_id bigint,
    version_id bigint NOT NULL,
    action varchar(12) NOT NULL CHECK (action IN ('import', 'publish', 'restore')),
    actor_id bigint REFERENCES users(id),
    reason varchar(1000) NOT NULL,
    created_at timestamptz NOT NULL,
    FOREIGN KEY (template_key, previous_version_id) REFERENCES document_template_versions(template_key, id),
    FOREIGN KEY (template_key, version_id) REFERENCES document_template_versions(template_key, id)
);
CREATE INDEX ix_document_template_activations_key ON document_template_activations(template_key, id DESC);
COMMIT;

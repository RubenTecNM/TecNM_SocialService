UPDATE academic_periods
SET school_year = CASE
    WHEN EXTRACT(MONTH FROM start_date) >= 8
        THEN EXTRACT(YEAR FROM start_date)::int::text || '-' || (EXTRACT(YEAR FROM start_date)::int + 1)::text
    ELSE (EXTRACT(YEAR FROM start_date)::int - 1)::text || '-' || EXTRACT(YEAR FROM start_date)::int::text
END
WHERE school_year IS NULL;

ALTER TABLE academic_periods
    ALTER COLUMN school_year SET NOT NULL;

DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ck_academic_periods__school_year'
    ) THEN
        ALTER TABLE academic_periods
            ADD CONSTRAINT ck_academic_periods__school_year
            CHECK (school_year ~ '^[0-9]{4}-[0-9]{4}$');
    END IF;
END $$;

